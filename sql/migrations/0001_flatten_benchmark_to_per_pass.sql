-- Reshape `benchmark` from "one row per run, with list-of-passes columns"
-- to "one row per pass" (one check_in_isabelle call), so each pass's
-- thy_content/verified/errors is a queryable/filterable scalar column
-- instead of living in parallel arrays indexed by position.
--
-- Run this in the Supabase SQL editor. Safe to run whether `benchmark`
-- already exists (in the old shape, or not at all) or not, since every
-- statement is idempotent (IF [NOT] EXISTS).
--
-- Adjust `exercise_id`'s type below if `exercise.id` isn't a bigint/serial
-- in your schema.

create table if not exists benchmark (
    id bigint generated by default as identity primary key,
    run_id uuid not null,
    pass_number integer not null,
    exercise_id bigint not null references exercise (id),
    model_name text not null,
    was_given_the_correct_thy_statement boolean not null default false,
    thy_content text not null,
    verified boolean not null,
    errors jsonb not null default '[]'::jsonb,
    max_num_of_passes integer not null,
    hit_retry_budget boolean not null default false,
    tokens_consumed integer not null default 0,
    created_at timestamptz not null default now()
);

-- In case `benchmark` already existed in the old, per-run/array shape:
alter table benchmark
    add column if not exists run_id uuid,
    add column if not exists pass_number integer,
    add column if not exists thy_content text,
    add column if not exists verified boolean,
    add column if not exists errors jsonb default '[]'::jsonb,
    add column if not exists max_num_of_passes integer,
    add column if not exists hit_retry_budget boolean not null default false,
    add column if not exists tokens_consumed integer not null default 0;

alter table benchmark
    drop column if exists thy_results,
    drop column if exists thoughts,
    drop column if exists deepisahol_metadata,
    drop column if exists num_of_passes,
    drop column if exists correctly_verified;

